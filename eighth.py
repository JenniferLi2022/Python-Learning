print("=== 基本操作 ===")
学生 = {"名字":"小王","年龄":20,"城市":"北京"}
print("字典：" + str(学生))
print("名字：" + 学生["名字"])
print("年龄：" + str(学生["年龄"]))

print("")

print("=== 修改值 ===")
学生["年龄"] = 21
学生["名字"] = "小李"
print("修改后：" + str(学生))

print("")

print("=== 添加新的键值对 ===")
学生["分数"] = 95
学生["学校"] = "清华"
print("添加后：" + str(学生))

print("")

print("=== 删除键值对 ===")
del 学生["学校"]
print("删除后：" + str(学生))

print("")

print("=== 遍历字典 ===")
for 键 in 学生:
    print(键 + "：" + str(学生[键]))

print("")

print("=== 获取所有键和值 ===")
print("所有键：" + str(list(学生.keys())))
print("所有值：" + str(list(学生.values())))

print("")

print("=== 多个字典 ===")
学生1 = {"名字":"小王","成绩":90}
学生2 = {"名字":"小红","成绩":85}
学生3 = {"名字":"小李","成绩":92}

学生列表 = [学生1,学生2,学生3]

for 学生 in 学生列表:
    print(学生["名字"] + " 的成绩是 " + str(学生["成绩"]))
